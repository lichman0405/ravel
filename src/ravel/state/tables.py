"""The PostgreSQL schema — RAVEL's authoritative Project State.

Two conventions shape every table here:

**Aggregate roots get columns; the values inside them get JSONB.** A Project,
a DAG node, an Evidence row, an Artifact version is an entity — it is queried,
joined, and referenced by identifier, so it gets real columns with real
constraints. The values *inside* an aggregate (`BudgetLimits`, `AuthorityCheck`,
`CriterionResult`, a list of dependency identifiers) are never queried on their
own, so they are stored as JSONB and reconstituted by the domain models that
already validate them. Spreading them into columns would add a second place
where their shape is defined, which is a second place it can be wrong.

**Every closed vocabulary becomes a CHECK constraint generated from the Python
enum.** The values are interpolated from `StrEnum` members at import time, so
the constraint cannot drift from the domain model, and a value added to an enum
without a migration fails the test suite rather than reaching production.

Rows are never deleted. See `ravel.state.guards` for the triggers that enforce
that, and for the database-level transition checks.
"""

