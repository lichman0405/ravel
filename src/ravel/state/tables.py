#: Deterministic constraint names. Without this, PostgreSQL invents names and
#: a migration cannot drop a constraint it cannot predictably name.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for every RAVEL table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def enum_check(column: str, vocabulary: type[StrEnum]) -> str:
    """A `CHECK` expression listing every value of a closed vocabulary.

    The values come from `StrEnum` members, never from user input, so the
    interpolation into SQL text carries no injection risk.
    """
    values = ", ".join(f"'{member.value}'" for member in vocabulary)
    return f"{column} IN ({values})"


def _enum_constraint(
    column: str, vocabulary: type[StrEnum], name: str | None = None
) -> CheckConstraint:
    """A named `CHECK` constraint over a closed vocabulary."""
    return CheckConstraint(enum_check(column, vocabulary), name=name or f"{column}_is_known")


#: UUID hex identifiers, generated by the domain layer.
ID = String(32)
#: Human-facing identifiers such as `P-1A2B3C4D`. Longer than an opaque id
#: because it carries a type prefix, and unique per table so a reader can quote
#: one unambiguously.
DISPLAY_ID = String(40)
#: Identifiers that may be supplied by a caller rather than generated.
REF = String(64)


